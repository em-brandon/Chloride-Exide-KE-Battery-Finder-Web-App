def _set_cell_shading(cell, fill_hex: str) -> None:
    """Set background fill color of a table cell."""
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill_hex)
    tc_pr.append(shd)


def _set_cell_text(cell, text: str, bold: bool = False, color_hex: Optional[str] = None) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    run = p.add_run(str(text) if text is not None else "")
    run.bold = bold
    if color_hex:
        run.font.color.rgb = None  # keep docx default object alive
        # python-docx expects RGBColor, but we avoid extra imports; set via XML
        rpr = run._r.get_or_add_rPr()
        color = OxmlElement("w:color")
        color.set(qn("w:val"), color_hex)
        rpr.append(color)


def _add_title(doc: Document, title: str, subtitle: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(title)
    run.bold = True
    run.font.size = Pt(22)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    p2 = doc.add_paragraph()
    run2 = p2.add_run(subtitle)
    run2.font.size = Pt(11)
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER


def _add_h2(doc: Document, text: str) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(14)


def _add_note(doc: Document, text: str) -> None:
    p = doc.add_paragraph(text)
    p.paragraph_format.space_after = Pt(6)


def _fmt_pct(v: Any) -> str:
    try:
        return f"{float(v):.1f}%"
    except Exception:
        return str(v)


def _fmt_num(v: Any) -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "—"
    try:
        if float(v).is_integer():
            return str(int(float(v)))
        return f"{float(v):.1f}"
    except Exception:
        return str(v)


def _add_table(doc: Document, df: pd.DataFrame, header_fill: str = "1F4E79") -> None:
    """Add a dataframe as a Word table with a colored header row."""
    if df is None or df.empty:
        doc.add_paragraph("(No data)")
        return

    table = doc.add_table(rows=1, cols=len(df.columns))
    table.style = "Table Grid"

    # Header
    hdr_cells = table.rows[0].cells
    for j, col in enumerate(df.columns):
        _set_cell_text(hdr_cells[j], str(col), bold=True, color_hex="FFFFFF")
        _set_cell_shading(hdr_cells[j], header_fill)

    # Body
    for _, row in df.iterrows():
        cells = table.add_row().cells
        for j, col in enumerate(df.columns):
            val = row.get(col)
            text = "—" if (val is None or (isinstance(val, float) and pd.isna(val))) else str(val)
            _set_cell_text(cells[j], text)


def _add_kpi_cards(doc: Document, summary_df: pd.DataFrame) -> None:
    """Add a compact KPI table for Select/Type/Overall."""
    wanted_cols = [
        "Input Type",
        "Total Cases",
        "Vehicle Match Accuracy %",
        "Spec Behaviour Accuracy %",
        "Avg Confidence",
    ]
    view = summary_df[[c for c in wanted_cols if c in summary_df.columns]].copy()

    # Make it readable: show % as strings
    if "Vehicle Match Accuracy %" in view.columns:
        view["Vehicle Match Accuracy %"] = view["Vehicle Match Accuracy %"].map(_fmt_pct)
    if "Spec Behaviour Accuracy %" in view.columns:
        view["Spec Behaviour Accuracy %"] = view["Spec Behaviour Accuracy %"].map(_fmt_pct)
    if "Avg Confidence" in view.columns:
        view["Avg Confidence"] = view["Avg Confidence"].map(_fmt_num)

    _add_table(doc, view, header_fill="2E7D32")


