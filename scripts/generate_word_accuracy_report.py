def _shade_pass_fail_in_table(table, pass_col_names: Iterable[str]) -> None:
    """Apply green/red shading for PASS/FAIL columns in a table."""
    # Find header index positions
    header = [c.text.strip() for c in table.rows[0].cells]
    idxs = [i for i, name in enumerate(header) if name in set(pass_col_names)]
    if not idxs:
        return

    for r in range(1, len(table.rows)):
        row = table.rows[r]
        for i in idxs:
            val = row.cells[i].text.strip().upper()
            if val == "PASS":
                _set_cell_shading(row.cells[i], "C8E6C9")  # light green
            elif val == "FAIL":
                _set_cell_shading(row.cells[i], "FFCDD2")  # light red


def main() -> int:
    xlsx_path = os.environ.get("IN_XLSX", DEFAULT_XLSX)
    out_path = os.environ.get("OUT_DOCX", DEFAULT_OUT)

    if not os.path.exists(xlsx_path):
        raise FileNotFoundError(f"Missing workbook: {xlsx_path}")

    # Load sheets (ignore if missing)
    def _read(sheet: str) -> Optional[pd.DataFrame]:
        try:
            return pd.read_excel(xlsx_path, sheet_name=sheet)
        except Exception:
            return None

    key_df = _read("Key")
    app_state_df = _read("App State")
    pipeline_df = _read("Pipeline Summary")
    checks_df = _read("Check Summary")
    rwf_df = _read("Real-World Failures")
    summary_df = _read("200-Case Summary")
    breakdown_df = _read("Failure Mode Breakdown")

    select_df = _read("200-Case Select")
    type_df = _read("200-Case Type")

    doc = Document()

    generated = datetime.now().strftime("%d %b %Y, %H:%M")
    _add_title(
        doc,
        "Battery Finder — Accuracy & Data Pipeline Report",
        f"Non-technical summary • Generated {generated}",
    )

    _add_note(
        doc,
        "This document explains the current state of the Battery Finder app, how the dataset pipelines feed it, "
        "and how accurate the recommendations are under a stress-test of 200 hard failure modes. "
        "It is based on the same structure as the Excel audit workbook (Key / Check Summary / Real-World Failures, etc.).",
    )

    _add_h2(doc, "Workbook Guide (What each sheet means)")
    _add_note(
        doc,
        "The Excel workbook is designed as an audit pack. Each sheet answers a simple question. "
        "This guide explains what each sheet is and how it was produced.",
    )
    _add_table(doc, _sheets_guide_df(), header_fill="263238")

    _add_h2(doc, "Method (How the 200-case test was built)")
    _add_note(
        doc,
        "We build 200 deterministic test cases from real dataset rows and then simulate difficult user inputs:\n"
        "• Select mode (100 cases): exact dropdown make/model/year from the dataset, but wrong optional CC/fuel values may be supplied to ensure the dataset remains authoritative.\n"
        "• Type mode (100 cases): the model text is deliberately made messy (typos, removed spaces/vowels, truncation), sometimes with a make typo and small year drift.\n"
        "The goal is not to ‘make the app fail’, but to measure how resilient it is to real user behavior.",
    )

    # 1) App state
    _add_h2(doc, "1) Current App State (What exists today)")
    if app_state_df is not None and not app_state_df.empty:
        _add_table(doc, app_state_df, header_fill="6A1B9A")  # purple
    else:
        _add_note(doc, "App State sheet was not found in the workbook.")

    # 2) Data pipelines
    _add_h2(doc, "2) Data Preparation Pipelines (Where the data comes from)")
    _add_note(
        doc,
        "The app depends on prepared CSV files. The pipelines clean raw data, enrich it with production years, and "
        "(for NTSA) enrich engine capacity (CC) and fuel type using public sources. The table below shows the key "
        "files and their sizes.",
    )
    if pipeline_df is not None and not pipeline_df.empty:
        _add_table(doc, pipeline_df, header_fill="0D47A1")  # deep blue

    # 3) How the matching works (Key sheet)
    _add_h2(doc, "3) How the App Matches Vehicles (Simple explanation)")
    _add_note(
        doc,
        "When a user searches for a vehicle, the system attempts to find the closest vehicle record in the dataset. "
        "It assigns a Match Type and a Confidence score. The definitions below are copied from the workbook’s Key sheet.",
    )
    if key_df is not None and not key_df.empty:
        _add_table(doc, key_df, header_fill="37474F")  # blue-grey

    # 4) Accuracy overview
    _add_h2(doc, "4) Accuracy Results (200 hard failure modes)")
    _add_note(
        doc,
        "We tested two input styles from the UI:\n"
        "• Select mode: user picks Make/Model/Year from dropdown lists\n"
        "• Type mode: user manually types Make/Model/Year (and must enter Engine CC + Fuel Type)\n"
        "The KPI table below summarizes accuracy for each.",
    )
    if summary_df is not None and not summary_df.empty:
        _add_kpi_cards(doc, summary_df)
    _add_pass_fail_explainer(doc)

    # 5) Check Summary (human readable)
    _add_h2(doc, "5) Check Summary (What we measure and why it matters)")
    if checks_df is not None and not checks_df.empty:
        _add_table(doc, checks_df, header_fill="1565C0")

    # 6) Real-world failures
    _add_h2(doc, "6) Real-World Failure Modes (Most important issues)")
    _add_note(
        doc,
        "These are the failure modes that most often cause wrong vehicle identification or reduced trust (low confidence). "
        "This section is intended for decision-makers: it’s the ‘what can go wrong’ list.",
    )
    if rwf_df is not None and not rwf_df.empty:
        _add_table(doc, rwf_df, header_fill="B71C1C")  # dark red

    # 7) Failure-mode breakdown
    _add_h2(doc, "7) Failure Mode Breakdown (Technical detail, still readable)")
    _add_note(
        doc,
        "The table below breaks accuracy down by failure mode (e.g., model truncation, removing spaces, year drift). "
        "Higher counts indicate more common stress cases; low accuracy indicates a weakness.",
    )
    if breakdown_df is not None and not breakdown_df.empty:
        _add_table(doc, breakdown_df.head(25), header_fill="4E342E")  # brown

    # 8) Appendix: sample failures (top 10 each)
    _add_h2(doc, "Appendix A — Example Cases (for audit and verification)")
    _add_note(
        doc,
        "Below are sample rows that failed the vehicle match check. This helps audit the test and understand common errors.",
    )

    def _sample_failures(df: Optional[pd.DataFrame], label: str) -> None:
        if df is None or df.empty:
            return
        fail = df[df.get("Vehicle Match ✓") == "FAIL"].copy() if "Vehicle Match ✓" in df.columns else pd.DataFrame()
        if fail.empty:
            doc.add_paragraph(f"{label}: No failures found.")
            return
        doc.add_paragraph(f"{label}: Showing up to 10 failed cases")
        cols = [
            "Case ID",
            "Failure Mode",
            "Input Make",
            "Input Model",
            "Input Year",
            "Expected Model",
            "Actual Matched Model",
            "Match Type",
            "Confidence",
            "Vehicle Match ✓",
            "Spec Behaviour ✓",
        ]
        view_cols = [c for c in cols if c in fail.columns]
        view = fail[view_cols].head(10)
        _add_table(doc, view, header_fill="455A64")

    _sample_failures(select_df, "Select mode")
    _sample_failures(type_df, "Type mode")

    doc.add_page_break()
    _add_note(doc, f"Source workbook: {os.path.basename(xlsx_path)}")

    doc.save(out_path)
    print(f"Wrote: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
